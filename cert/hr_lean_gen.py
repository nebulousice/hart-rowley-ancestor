"""Generate lean/Pipeline/HartRowley/Data.lean: untrusted hint data for the Lean check.

Every datum written here is RE-VERIFIED inside Lean by `decide +kernel`
(see lean/Pipeline/HartRowley/Main.lean): the element list (strictly increasing,
hence distinct; first entry = identity), the right-multiplication table (each entry
recomputed from the permutations), the length table (equal to the BFS distance
recomputed in Lean), and the involution list (equal to the filter recomputed in Lean).
So a wrong datum makes the Lean build fail; it cannot make a false theorem pass.

Model: H3 acting on its 30 roots (r1 -5- r2 - r3), from hr_tables.Group.
Usage: python hr_lean_gen.py <output Data.lean path>
"""
import sys
from collections import deque
import hr_tables as h

G = h.Group('H', 3)
gens = [list(g) for g in G.gen]
elems = sorted(list(e) for e in G.elems)
assert elems[0] == list(range(30))
index = {tuple(e): i for i, e in enumerate(elems)}

def mul(p, q):              # (p*q)(k) = p(q(k)), same convention as Main.lean
    return [p[k] for k in q]

right = [[index[tuple(mul(e, g))] for g in gens] for e in elems]
dist = [None] * len(elems)
dist[0] = 0
q = deque([0])
while q:
    x = q.popleft()
    for y in right[x]:
        if dist[y] is None:
            dist[y] = dist[x] + 1
            q.append(y)
one = list(range(30))
invol = [i for i, e in enumerate(elems) if i != 0 and mul(e, e) == one]

def lst(xs):
    return '[' + ', '.join(str(x) for x in xs) + ']'

out = []
out.append('/-! Generated by targets/hart-rowley-ancestor/cert/hr_lean_gen.py -- do not edit.')
out.append('Hint data only: every entry is re-verified in Main.lean by `decide +kernel`. -/')
out.append('')
out.append('namespace HartRowley')
out.append('')
for i, g in enumerate(gens):
    out.append('/-- generator r%d as a permutation of the 30 roots of H3 -/' % (i + 1))
    out.append('def s%d : List Nat := %s' % (i + 1, lst(g)))
out.append('')
out.append('/-- the 120 group elements, lexicographically increasing -/')
out.append('def elemsData : List (List Nat) := [')
out.append(',\n'.join('  ' + lst(e) for e in elems))
out.append(']')
out.append('')
out.append('/-- rightData[i][j] = index of elems[i] * s_{j+1} -/')
out.append('def rightData : List (List Nat) := [')
out.append(',\n'.join('  ' + lst(r) for r in right))
out.append(']')
out.append('')
out.append('/-- claimed Coxeter lengths -/')
out.append('def lenData : List Nat := %s' % lst(dist))
out.append('')
out.append('/-- claimed indices of the involutions -/')
out.append('def involData : List Nat := %s' % lst(invol))
out.append('')
out.append('end HartRowley')
out.append('')
open(sys.argv[1], 'w', newline='\n').write('\n'.join(out))
print('wrote %s: %d elements, %d involutions, max length %d' % (sys.argv[1], len(elems), len(invol), max(dist)))
